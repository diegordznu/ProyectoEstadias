-- Esquema de inventario y movimientos entre plantas.
-- Reemplaza los datos fijos del frontend (MATERIALS y MOVEMENTS en App.tsx).
-- Ejecutar después de 01_usuarios.sql (movimientos.usuario_id apunta a usuarios).
--
-- Seguridad: igual que usuarios, las tablas tienen RLS activo y sin políticas.
-- El backend se conecta como "postgres" (tiene BYPASSRLS) y puede leer/escribir;
-- la API pública de Supabase (anon / authenticated) no ve nada.

-- Tabla anterior, sustituida por la vista v_inventario (el inventario se calcula, no se guarda).
DROP TABLE IF EXISTS public.inventario;

-- ---------------------------------------------------------------------------
-- Catálogo de materiales
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.materiales (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku     VARCHAR(30)  NOT NULL,
    nombre  VARCHAR(120) NOT NULL,
    estatus BOOLEAN      NOT NULL DEFAULT true,          -- true = activo
    CONSTRAINT materiales_sku_key       UNIQUE (sku),
    CONSTRAINT materiales_sku_no_vacio  CHECK (btrim(sku) <> '')
);
ALTER TABLE public.materiales ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- Ubicaciones: todo lo que puede ser ORIGEN o DESTINO de un movimiento.
--   PLANTA    → Planta 1, 2, 3, 6 (lleva existencias; puede ser origen y destino)
--   PROVEEDOR → proveedores externos (solo origen: entrada al sistema)
--   CONSUMO   → destinos externos   (solo destino: salida del sistema)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ubicaciones (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(80) NOT NULL,
    tipo    VARCHAR(10) NOT NULL,
    estatus BOOLEAN     NOT NULL DEFAULT true,           -- true = activa
    CONSTRAINT ubicaciones_nombre_key      UNIQUE (nombre),
    CONSTRAINT ubicaciones_nombre_no_vacio CHECK (btrim(nombre) <> ''),
    CONSTRAINT ubicaciones_tipo_check      CHECK (tipo IN ('PLANTA', 'PROVEEDOR', 'CONSUMO')),
    -- Necesario para que movimientos valide el tipo con una llave foránea compuesta.
    CONSTRAINT ubicaciones_id_tipo_key     UNIQUE (id, tipo)
);
ALTER TABLE public.ubicaciones ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- Movimientos: cada entrada, traspaso o consumo se captura UNA sola vez.
-- Las tablas por planta, el historial y el inventario se obtienen de aquí.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.movimientos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        TIMESTAMP    NOT NULL,                  -- año, mes, día, hora y minuto
    material_id  BIGINT       NOT NULL,
    lote         VARCHAR(30)  NOT NULL,
    origen_id    BIGINT       NOT NULL,
    origen_tipo  VARCHAR(10)  NOT NULL,
    destino_id   BIGINT       NOT NULL,
    destino_tipo VARCHAR(10)  NOT NULL,
    cantidad     INTEGER      NOT NULL,
    usuario_id   INTEGER,                                -- quién lo capturó
    creado_en    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT movimientos_material_fkey FOREIGN KEY (material_id) REFERENCES public.materiales (id),
    CONSTRAINT movimientos_usuario_fkey  FOREIGN KEY (usuario_id)  REFERENCES public.usuarios (id),
    -- El tipo guardado debe coincidir con el de la ubicación: así la BD impide,
    -- por ejemplo, poner un proveedor como destino o un consumo como origen.
    CONSTRAINT movimientos_origen_fkey   FOREIGN KEY (origen_id,  origen_tipo)  REFERENCES public.ubicaciones (id, tipo),
    CONSTRAINT movimientos_destino_fkey  FOREIGN KEY (destino_id, destino_tipo) REFERENCES public.ubicaciones (id, tipo),
    CONSTRAINT movimientos_origen_tipo_check  CHECK (origen_tipo  IN ('PLANTA', 'PROVEEDOR')),
    CONSTRAINT movimientos_destino_tipo_check CHECK (destino_tipo IN ('PLANTA', 'CONSUMO')),
    CONSTRAINT movimientos_origen_distinto    CHECK (origen_id <> destino_id),
    -- Al menos un lado es planta (un proveedor no puede enviar directo a consumo).
    CONSTRAINT movimientos_toca_planta        CHECK (origen_tipo = 'PLANTA' OR destino_tipo = 'PLANTA'),
    CONSTRAINT movimientos_cantidad_positiva  CHECK (cantidad > 0),
    CONSTRAINT movimientos_lote_no_vacio      CHECK (btrim(lote) <> '')
);
ALTER TABLE public.movimientos ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_movimientos_fecha    ON public.movimientos (fecha DESC);
CREATE INDEX IF NOT EXISTS idx_movimientos_origen   ON public.movimientos (origen_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_movimientos_destino  ON public.movimientos (destino_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_movimientos_material ON public.movimientos (material_id);

-- ---------------------------------------------------------------------------
-- Vista con los nombres ya resueltos: alimenta las tablas de cada planta
-- (WHERE origen = 'Planta 1' OR destino = 'Planta 1') y el historial.
-- security_invoker: la vista respeta el RLS de las tablas (no las expone a la API pública).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.v_movimientos WITH (security_invoker = true) AS
SELECT mv.id,
       mv.fecha,
       ma.sku     AS material,
       mv.lote,
       uo.nombre  AS origen,
       ud.nombre  AS destino,
       mv.cantidad
FROM public.movimientos mv
JOIN public.materiales  ma ON ma.id = mv.material_id
JOIN public.ubicaciones uo ON uo.id = mv.origen_id
JOIN public.ubicaciones ud ON ud.id = mv.destino_id;

-- ---------------------------------------------------------------------------
-- Inventario calculado: destino suma, origen resta (misma regla que el frontend).
-- Una fila por material y planta, incluidas las que quedan en 0.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.v_inventario WITH (security_invoker = true) AS
WITH efectos AS (
    SELECT material_id, destino_id AS ubicacion_id,  cantidad AS delta FROM public.movimientos
    UNION ALL
    SELECT material_id, origen_id  AS ubicacion_id, -cantidad AS delta FROM public.movimientos
)
SELECT ma.sku,
       ma.nombre,
       pl.nombre                  AS planta,
       COALESCE(SUM(e.delta), 0)  AS existencia
FROM public.materiales  ma
CROSS JOIN public.ubicaciones pl
LEFT JOIN efectos e ON e.material_id = ma.id AND e.ubicacion_id = pl.id
WHERE pl.tipo = 'PLANTA'
GROUP BY ma.sku, ma.nombre, pl.nombre;

-- ---------------------------------------------------------------------------
-- Datos iniciales de ubicaciones
-- ---------------------------------------------------------------------------
INSERT INTO public.ubicaciones (nombre, tipo) VALUES
    ('Planta 1', 'PLANTA'),
    ('Planta 2', 'PLANTA'),
    ('Planta 3', 'PLANTA'),
    ('Planta 6', 'PLANTA'),
    ('Consumo',  'CONSUMO')
ON CONFLICT (nombre) DO NOTHING;
